const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1600,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  let mode='iep',step=0,outputs=[];
  const call=(name,args)=>({type:'function_call',name,namespace:'careit',call_id:`call_${step}`,arguments:JSON.stringify(args)});
  await page.route('**/careit-mockup.html',route=>route.fulfill({status:200,contentType:'text/html',body:fs.readFileSync(path.join(__dirname,'careit-mockup.html'))}));
  await page.route('**/api/local-ai/**',async route=>{
    const path=new URL(route.request().url()).pathname;
    let result;
    if(path.endsWith('/status'))result={connected:true,usage:{limit:500000,used:50000,remaining:450000,resetAt:'2026-11-22T15:00:00Z'}};
    else if(path.endsWith('/models'))result={models:[{slug:'gpt-6-luna',name:'GPT-6 Luna'}]};
    else if(path.endsWith('/respond')){
      const body=route.request().postDataJSON();outputs.push(...body.turn.filter(item=>item.type==='function_call_output').slice(-1).map(item=>JSON.parse(item.output)));
      const calls=mode==='iep'?[['interact',{action:'navigate',target:'IEP',value:''}],['interact',{action:'select',target:'성별',value:'여성'}],['interact',{action:'click',target:'현재학습수행수준',value:''}],['interact',{action:'fill',target:'현재 수행 모습',value:'그림을 가리켰다.'}]]:mode==='search'?[['search_journals',{query:'테스트나비',person:''}]]:mode==='back'?[['interact',{action:'navigate',target:'IEP',value:''}]]:[];
      result=step<calls.length?{text:'',output:[call(...calls[step++])]}:{text:({iep:'입력했어요.',search:'일지를 찾았어요.',diary:'일지를 열었어요.',back:'IEP를 열었어요.'})[mode],output:[]};
    }else result={};
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(result)});
  });
  try{
    await page.goto('http://127.0.0.1:8767/careit-mockup.html#/');
    await page.evaluate(async()=>{const b=window.__careitAiBridge;b.state.savedJournals.unshift({recipient:0,date:'2026-11-05',text:'테스트나비를 관찰했다.'},{recipient:0,date:'2026-11-04',text:'테스트나비 그림을 그렸다.'});await b.store.save(JSON.stringify(b.state));});
    await page.locator('.sidebar [data-action="ai-toggle"]').click();
    await page.waitForTimeout(500);
    assert.equal(await page.locator('[data-ai-weekly-usage]').count(),0);
    await page.getByRole('button',{name:'첨부 및 사용량'}).click();
    assert.match(await page.locator('[data-ai-weekly-usage]').innerText(),/90% 남음/);
    let menu=await page.locator('.ai-attach-menu').boundingBox(),composer=await page.locator('#ai-chat-form').boundingBox();
    assert(menu.y+menu.height<=composer.y-7,'Menu overlaps the composer on desktop');
    assert.equal(await page.getByRole('button',{name:'사진 및 파일 첨부'}).count(),1);
    assert.equal(await page.locator('.ai-weekly-meter').count(),0);
    await page.getByRole('button',{name:'첨부 및 사용량'}).click();
    assert.equal(await page.locator('[data-ai-weekly-usage]').count(),0);
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'첨부 및 사용량'}).click();
    menu=await page.locator('.ai-attach-menu').boundingBox();composer=await page.locator('#ai-chat-form').boundingBox();
    assert(menu.y+menu.height<=composer.y-7,'Menu overlaps the composer on mobile');
    await page.getByRole('button',{name:'첨부 및 사용량'}).click();
    await page.setViewportSize({width:1600,height:900});
    await page.getByRole('button',{name:'첨부 및 사용량'}).click();
    const [chooser]=await Promise.all([page.waitForEvent('filechooser'),page.getByRole('button',{name:'사진 및 파일 첨부'}).click()]);
    await chooser.setFiles({name:'test.txt',mimeType:'text/plain',buffer:Buffer.from('test')});
    assert.equal(await page.locator('[data-action="ai-chat-remove-file"]').count(),1);
    await page.locator('[data-action="ai-chat-remove-file"]').click();
    await page.locator('#ai-chat-input').fill('IEP 현재 수행 모습에 그림을 가리켰다. 입력해줘');
    await page.locator('#ai-chat-form').evaluate(form=>form.requestSubmit());
    await page.getByText('입력했어요.',{exact:true}).waitFor();
    assert.equal(await page.locator('#iew-current').inputValue(),'그림을 가리켰다.');
    assert(outputs.every(result=>result.ok),JSON.stringify(outputs));
    await page.locator('[data-iew-id="personal"]').click();
    assert.equal(await page.locator('#iew-sex').inputValue(),'여성');
    await page.locator('[data-iew-id="current"]').click();
    assert.equal(await page.locator('#iew-current').inputValue(),'그림을 가리켰다.');
    mode='search';step=0;outputs=[];
    await page.locator('#ai-chat-input').fill('테스트나비 일지 찾아줘');
    await page.locator('#ai-chat-form').evaluate(form=>form.requestSubmit());
    await page.getByText('일지를 찾았어요.',{exact:true}).waitFor();
    assert.equal(outputs.at(-1).total,2);
    assert.equal(await page.locator('.ai-chat-choice[href*="/journals/new"]').count(),2);
    mode='diary';step=0;outputs=[];
    await page.evaluate(()=>{const store=window.__careitAiBridge.store;window.__testSave=store.save;store.save=async()=>false;});
    await page.locator('#ai-chat-input').fill('오늘 일지 작성 도와줘');
    await page.locator('#ai-chat-form').evaluate(form=>form.requestSubmit());
    await page.getByText('IEP를 저장하지 못해 이동하지 않았어요. 다시 확인해 주세요.',{exact:true}).waitFor();
    assert.match(page.url(),/#\/iep/);
    assert.equal(await page.locator('#iew-current').inputValue(),'그림을 가리켰다.');
    await page.evaluate(()=>{window.__careitAiBridge.store.save=window.__testSave;});
    await page.locator('#ai-chat-input').fill('오늘 일지 작성 도와줘');
    await page.locator('#ai-chat-form').evaluate(form=>form.requestSubmit());
    await page.getByText('일지를 열었어요.',{exact:true}).waitFor();
    assert.match(page.url(),/#\/journals\/new/);
    const plan=await page.evaluate(()=>window.__careitAiBridge.state.iep.semesterPlans[0]);
    assert.equal(plan.savedRevision,plan.revision);
    await page.locator('#journal-raw').fill('저장 이동 테스트');
    mode='back';step=0;outputs=[];
    await page.locator('#ai-chat-input').fill('IEP 열어줘');
    await page.locator('#ai-chat-form').evaluate(form=>form.requestSubmit());
    await page.getByText('IEP를 열었어요.',{exact:true}).waitFor();
    assert.match(page.url(),/#\/iep/);
    assert(await page.evaluate(()=>window.__careitAiBridge.state.savedJournals.some(row=>row.text.includes('저장 이동 테스트'))));
    assert(outputs.at(-1).message.includes('일지를 저장하고'));
    assert.deepEqual(errors,[]);
    console.log('AI screen controls and local journal search: passed');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
