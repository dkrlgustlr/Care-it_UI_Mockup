const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});page.setDefaultTimeout(8000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'#/iep');
  await page.getByRole('button',{name:'양식 편집',exact:true}).click();
  const card=page.locator('[data-builder-section="builtin:personal:main"]'),modal=page.locator('#mockup-dialog');
  await card.getByRole('button',{name:'+ 항목 추가'}).click();
  assert.equal(await modal.locator('[data-builder-settings="text"]').isVisible(),true);
  assert.equal(await modal.locator('[data-builder-settings="choice"]').isVisible(),false);
  await modal.locator('#iew-builder-type-button').click();
  const picker=page.locator('#quick-type-picker');
  assert.equal(await picker.locator('.quick-check-type-card').count(),7);
  await picker.getByText('숫자',{exact:true}).click();
  await picker.getByRole('button',{name:'취소',exact:true}).click();
  assert.equal(await modal.locator('#iew-builder-type-button').innerText(),'텍스트');
  await modal.locator('#iew-builder-type-button').click();
  await picker.getByText('선택형',{exact:true}).click();
  await picker.getByRole('button',{name:'저장',exact:true}).click();
  assert.equal(await modal.locator('[data-builder-settings="choice"]').isVisible(),true);
  assert.equal(await modal.locator('[data-builder-settings="text"]').isVisible(),false);
  assert.equal(await modal.getByRole('button',{name:'추가',exact:true}).isDisabled(),true);
  await modal.getByRole('button',{name:'취소',exact:true}).click();
  async function add(name,type,configure){
   await card.getByRole('button',{name:'+ 항목 추가'}).click();
   await modal.locator('#iew-builder-name').fill(name);
   await modal.locator('#iew-builder-type-button').click();
   await picker.getByText(type==='시간 길이'?'소요 시간':type,{exact:true}).click();
   await picker.getByRole('button',{name:'저장',exact:true}).click();
   if(configure)await configure();
   await modal.getByRole('button',{name:'추가',exact:true}).click();
  }
  await add('별명','텍스트',async()=>modal.getByText('짧은 글',{exact:true}).click());
  assert.equal(await page.getByLabel('별명',{exact:true}).evaluate(el=>el.tagName),'INPUT');
  await page.getByLabel('별명',{exact:true}).fill('하늘');
  await add('필요 지원','선택형',async()=>{await modal.locator('#iew-builder-options').fill('시각 자료\n말로 안내');await modal.getByText('여러 개 선택',{exact:true}).click();});
  await page.getByText('시각 자료',{exact:true}).click();await page.getByText('말로 안내',{exact:true}).click();
  assert.equal(await page.getByLabel('시각 자료',{exact:true}).isChecked(),true);
  assert.equal(await page.getByLabel('말로 안내',{exact:true}).isChecked(),true);
  await add('방문 시각','시각');
  await page.getByRole('button',{name:'방문 시각',exact:true}).click();
  await page.getByRole('option',{name:'오후',exact:true}).click();
  await page.getByLabel('방문 시각 시',{exact:true}).fill('9');
  await page.getByLabel('방문 시각 분',{exact:true}).fill('30');
  await add('지원 시간','시간 길이');
  await page.getByLabel('지원 시간 시간',{exact:true}).fill('1');
  await page.getByLabel('지원 시간 분',{exact:true}).fill('20');
  await page.getByLabel('지원 시간 초',{exact:true}).fill('0');
  await add('지원 횟수','숫자',async()=>modal.locator('#iew-builder-unit').fill('회'));
  await page.getByLabel('지원 횟수',{exact:true}).fill('4');
  await add('지원 수준','척도',async()=>{await modal.locator('#iew-builder-min').fill('2');await modal.locator('#iew-builder-max').fill('20');assert.equal(await modal.getByRole('button',{name:'추가',exact:true}).isDisabled(),true);await modal.locator('#iew-builder-max').fill('4');});
  assert.equal(await page.getByRole('button',{name:'지원 수준 3'}).getAttribute('aria-pressed'),'false');
  await page.getByRole('button',{name:'지원 수준 3'}).click();
  assert.equal(await page.getByRole('button',{name:'지원 수준 3'}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'완료',exact:true}).click();await page.locator('[data-iew-action="save"]').click();await page.reload();
  assert.equal(await page.getByLabel('별명',{exact:true}).inputValue(),'하늘');
  assert.equal(await page.getByLabel('시각 자료',{exact:true}).isChecked(),true);
  assert.equal(await page.getByLabel('말로 안내',{exact:true}).isChecked(),true);
  assert.equal(await page.getByLabel('방문 시각 시',{exact:true}).inputValue(),'9');
  assert.equal(await page.getByLabel('방문 시각 분',{exact:true}).inputValue(),'30');
  assert.equal(await page.getByLabel('지원 시간 시간',{exact:true}).inputValue(),'1');
  assert.equal(await page.getByLabel('지원 시간 분',{exact:true}).inputValue(),'20');
  assert.equal(await page.getByLabel('지원 시간 초',{exact:true}).inputValue(),'0');
  assert.equal(await page.getByLabel('지원 횟수',{exact:true}).inputValue(),'4');
  assert.equal(await page.getByRole('button',{name:'지원 수준 3'}).getAttribute('aria-pressed'),'true');
  await page.locator('[data-iew-id="document"]').click();
  const text=await page.locator('#iew-content').innerText();
  for(const value of ['하늘','시각 자료, 말로 안내','오후 9시 30분','1시간 20분 0초','4 회'])assert.ok(text.includes(value),value);
  assert.deepEqual(errors,[]);
  console.log('IEP journal-style field types, values and output: passed');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
