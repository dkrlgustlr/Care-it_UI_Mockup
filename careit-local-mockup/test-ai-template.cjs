const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ channel:'chrome', headless:true });
  const page = await browser.newPage({ viewport:{ width:1440, height:900 } });
  page.setDefaultTimeout(8000);
  page.on('pageerror', error => console.error(error));
  const send = async text => { await page.locator('#ai-chat-input').fill(text); await page.locator('#ai-chat-input').press('Enter'); };
  try {
    await page.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'#/ai-chat');
    await send('일지 양식 편집해줘');
    await page.locator('[data-action="ai-chat-choice"]').first().click();
    const journal = page;
    const label = journal.locator('#configuration-label-1');
    await label.waitFor();
    const original = await label.inputValue();
    await send(`“${original}”을 “놀이 기록”으로 바꿔줘`);
    await label.waitFor();
    await page.waitForFunction(() => document.querySelector('.ai-chat-messages')?.textContent.includes('일지 양식 초안에 반영'));
    assert.equal(await label.inputValue(), '놀이 기록');
    const before = await page.evaluate(() => window.__careitAiBridge.state.journalTemplateConfigs[0]?.labels?.[1]);
    assert.notEqual(before, '놀이 기록');
    await page.locator('.sidebar nav a[data-route="/"]').click();
    await page.locator('#mockup-dialog [data-action="confirm-dialog"]').click();
    await page.waitForFunction(() => window.__careitAiBridge.state.journalTemplateConfigs[0]?.labels?.[1] === '놀이 기록');
    await page.waitForURL(/#\/$/);
    await page.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'#/ai-chat');

    await send('새 리포트 채점 기준 만들어줘');
    await page.getByText(/어떤 상황이나 영역/).waitFor();
    await send('자유 놀이에서 의사소통을 관찰하고 싶어');
    const score = page;
    await score.locator('#score-edit-form').waitFor();
    await page.getByText(/고정된 예시 문항을 초안으로/).waitFor();
    assert.equal(await score.locator('.score-area-option').count(), 3);
    assert.equal(await score.locator('.score-question-list textarea').count(), 15);
    assert.equal(await page.evaluate(() => (window.__careitAiBridge.state.customReportTemplates||[]).length), 0);
    await send('“활동 중 도움을 요청한다.” 추가해줘');
    await page.getByText(/문항을 초안에 추가/).waitFor();
    assert.equal(await score.locator('.score-question-list textarea').count(), 16);
    await score.locator('#score-edit-form button[type="submit"]:visible').click();
    await page.locator('#ai-dock').getByText(/새 리포트 기준을 저장했어요/).waitFor();
    const custom = await page.evaluate(() => window.__careitAiBridge.state.customReportTemplates);
    assert.equal(custom.length, 1);
    assert.ok(custom[0].domains[0].questions.includes('활동 중 도움을 요청한다.'));
    await send('다른 리포트 채점 기준 편집해줘');
    await page.getByRole('button', {name:'놀이 관찰 기준',exact:true}).click();
    const existing = page;
    await existing.locator('#score-edit-form').waitFor();
    await send('“의사소통”을 “의사 표현”으로 바꿔줘');
    await page.getByText(/리포트 기준 초안에 반영/).waitFor();
    assert.equal(await existing.locator('#score-domain-title-0').inputValue(), '의사 표현');
    assert.equal(await page.evaluate(() => window.__careitAiBridge.state.customReportTemplates[0].domains[0].name), '의사소통');
    await page.locator('.sidebar nav a[data-route="/"]').click();
    await page.locator('#mockup-dialog[open]').waitFor();
    assert.equal(await page.locator('#mockup-dialog [data-action="discard-and-move"]').count(), 1);
    await page.locator('#mockup-dialog [data-action="close-dialog"]').click();
    assert.equal(await existing.locator('#score-domain-title-0').inputValue(), '의사 표현');
    await page.locator('.sidebar nav a[data-route="/"]').click();
    await page.locator('#mockup-dialog [data-action="confirm-dialog"]').click();
    await page.waitForFunction(() => window.__careitAiBridge.state.reportTemplateConfigs?.[3]?.domains[0].name === '의사 표현');
    await page.waitForURL(/#\/$/);
    await page.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'#/recipients?tab=report');
    await page.getByRole('heading', {name:'놀이 관찰 기준'}).waitFor();
    const mobile = await browser.newPage({viewport:{width:390,height:844}});
    mobile.setDefaultTimeout(8000);
    await mobile.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'?previewMode=app#/ai-chat');
    await mobile.locator('#ai-chat-input').fill('일지 양식 편집해줘');
    await mobile.locator('#ai-chat-input').press('Enter');
    await mobile.locator('[data-action="ai-chat-choice"]').first().click();
    const mobileLabel=mobile.locator('#configuration-label-1');
    await mobileLabel.waitFor();
    const mobileOriginal=await mobileLabel.inputValue();
    await mobile.locator('#ai-chat-input').fill(`“${mobileOriginal}”을 “놀이 기록”으로 바꿔줘`);
    await mobile.locator('#ai-chat-input').press('Enter');
    await mobile.getByText(/일지 양식 초안에 반영/).waitFor();
    await mobile.getByRole('button',{name:'케어릿 AI 닫기'}).click();
    assert.equal(await mobileLabel.inputValue(),'놀이 기록');
    await mobile.close();
    console.log('AI template editing and saving: passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
