// Run with Node and an installed Playwright/Chrome. Uses an isolated browser profile.
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = pathToFileURL(path.join(__dirname, 'careit-mockup.html')).href;
  const visit = async hash => { await page.goto(base + hash); };
  const storageKey = 'careit-ui-mockup-20260923-v1';

  await visit('#/recipients');
  assert.match(await page.locator('.recipient-list-heading').innerText(), /5\/5/);
  await page.locator('[data-action="add-recipient"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /한도/);
  await page.locator('#mockup-dialog [data-action="close-dialog"]').click();

  await visit('#/journals/new?recipient=0&entry=0');
  const oldQuickName = await page.locator('[data-quick-checks] legend span').first().innerText();
  await visit('#/settings/configuration?recipient=0&template=1');
  await page.locator('[data-action="edit-quick-check"]').first().click();
  await page.locator('#quick-dialog [data-action="close-modal"]').click();
  assert.equal(await page.locator('#quick-dialog').evaluate(el=>el.open),false);
  await page.locator('[data-action="edit-quick-check"]').first().click();
  await page.locator('#quick-name').fill('변경 중');
  await page.locator('#quick-dialog [data-action="close-modal"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /변경 내용을 저장할까요/);
  await page.locator('#mockup-dialog [data-action="discard-and-close"]').click();
  await page.locator('[data-action="edit-quick-check"]').first().click();
  await page.locator('#quick-name').fill('검증용 새 퀵체크');
  await page.locator('#quick-dialog button[type="submit"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /공통 퀵체크를 사용하는/);
  await page.locator('#mockup-dialog [data-action="confirm-dialog"]').click();
  await page.waitForSelector('#quick-dialog:not([open])', { state: 'attached' });
  await visit('#/journals/new?recipient=0&entry=0');
  assert.equal(await page.locator('[data-quick-checks] legend span').first().innerText(), oldQuickName);
  await visit('#/journals/new?recipient=0');
  assert.equal(await page.locator('[data-quick-checks] legend span').first().innerText(), '검증용 새 퀵체크');

  const priorReport = {id:'saved-test',recipient:0,from:'2026-10-23',to:'2026-10-29',generated:'2026-10-30',mock:true,scoring:{title:'이전 기준',domains:[{name:'이전 영역',questions:['이전 문항']}]}};
  await page.evaluate(({key,report}) => { const s=JSON.parse(localStorage.getItem(key)); s.generatedReports=[report]; s.scoring[3]={title:'누리과정',domains:[{name:'개별 영역',questions:['개별 문항']}]}; s.quickChecks[3]=[{name:'개별 퀵체크',type:'텍스트',active:true,choices:[],maxLength:200}]; s.savedJournals.push({recipient:3,date:'2026-11-06',text:'개별 설정으로 작성한 일지',values:{'quick-0':'기록'}}); localStorage.setItem(key,JSON.stringify(s)); },{key:storageKey,report:priorReport});
  await visit('#/recipients?tab=report');
  await page.reload();
  await page.locator('[data-action="report-template-edit"]').first().click();
  await page.locator('.score-area-panel:visible').waitFor();
  assert.equal(await page.locator('.score-editor-info').count(), 0);
  assert.equal(await page.locator('.score-area-panel:visible').count(),1);
  assert.equal(await page.locator('.score-editor-top [data-options="score-templates"]').count(),1);
  await page.locator('#score-question-0-0').fill('새로운 공통 문항');
  await page.locator('#score-edit-form button[type="submit"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /공통 기준을 사용하는/);
  await page.locator('#mockup-dialog [data-action="confirm-dialog"]').click();
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).reportTemplateConfigs?.[0]?.domains[0].questions[0]==='새로운 공통 문항',storageKey);
  assert.deepEqual(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).generatedReports[0],storageKey),priorReport);
  await page.locator('.score-editor-back').click();

  await visit('#/recipients?tab=recipients');
  await page.locator('[data-action="edit-recipient-card"][data-index="3"]').click();
  await page.locator('#recipient-journal-template').click();
  await page.getByRole('option',{name:'일지 템플릿 2'}).click();
  await page.locator('#recipient-report-template').click();
  await page.getByRole('option',{name:'사고·사회 참여'}).click();
  await page.locator('#recipient-form button[type="submit"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /개별 설정이 선택한 공통 템플릿으로/);
  await page.locator('#mockup-dialog [data-action="confirm-dialog"]').click();
  await page.waitForSelector('.recipient-form-dialog:not([open])',{state:'attached'});
  const afterReplacement=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),storageKey);
  assert.equal(afterReplacement.recipients[3].templateIndex,1);
  assert.equal(afterReplacement.reportTemplates[3],'사고·사회 참여');
  assert.equal(afterReplacement.quickChecks[3],undefined);
  assert.equal(afterReplacement.scoring[3],undefined);
  await visit('#/journals/new?recipient=3&entry=0');
  assert.equal(await page.locator('[data-quick-checks] legend span').first().innerText(),'개별 퀵체크');

  await page.evaluate(key => { const s = JSON.parse(localStorage.getItem(key)); s.subscription = null; s.planDemoFree = true; localStorage.setItem(key, JSON.stringify(s)); }, storageKey);
  await visit('#/');
  await page.reload();
  await page.waitForSelector('[data-action="choose-active-recipients"]');
  assert.match(await page.locator('.recipient-list-heading').innerText(), /5\/1/);
  await page.locator('[data-action="choose-active-recipients"]').click();
  const keep = page.locator('#recipient-choose-dialog input');
  assert.equal(await keep.count(), 5);
  await keep.nth(0).check();
  await keep.nth(1).check();
  assert.equal(await page.locator('[data-action="save-active-recipients"]').isDisabled(), true);
  await keep.nth(1).uncheck();
  await page.locator('[data-action="save-active-recipients"]').click();
  await page.waitForSelector('#recipient-choose-dialog:not([open])', { state: 'attached' });
  assert.match(await page.locator('.recipient-list-heading').innerText(), /1\/1/);
  assert.equal(await page.locator('.recipient-memo-card.is-inactive').count(), 4);
  await page.locator('.recipient-memo-card.is-inactive [data-action="edit-recipient-card"]').first().click();
  await page.locator('[data-action="form-toggle-recipient"]').click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /한도/);
  await page.locator('#mockup-dialog [data-action="close-dialog"]').click();
  await page.locator('#recipient-name').fill('저장하지 않은 이름');
  await page.locator('.recipient-form-dialog [data-action="cancel-recipient"]').first().click();
  assert.match(await page.locator('#mockup-dialog').innerText(), /저장하지 않고 닫기/);
  await page.locator('#mockup-dialog [data-action="close-dialog"]').click();
  assert.equal(await page.locator('#recipient-name').inputValue(),'저장하지 않은 이름');
  assert.deepEqual(errors, []);
  const mobileContext = await browser.newContext({viewport:{width:360,height:800}});
  const mobile = await mobileContext.newPage();
  await mobile.goto(base+'#/recipients');
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mobile.goto(base+'#/settings/configuration?recipient=0&template=1');
  const picker=await mobile.locator('#configuration-template-select').boundingBox();
  const name=await mobile.locator('#template-name').boundingBox();
  assert.ok(name.y<picker.y && picker.x+picker.width<=360 && name.x+name.width<=360);
  await mobile.locator('#configuration-template-select').click();
  assert.equal(await mobile.getByRole('option',{name:'일지 템플릿 2'}).isVisible(),true);
  await mobileContext.close();
  await context.close();
  await browser.close();
  console.log('Recipient quota, manual selection and saved journal schema checks passed.');
})().catch(error => { console.error(error); process.exit(1); });
