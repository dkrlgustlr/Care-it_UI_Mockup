const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, 'careit-mockup.html'), 'utf8');
const source = html.split('<script id="mockup-runtime">')[1].split('(() => {')[0];
const context = vm.createContext({});
vm.runInContext(source, context);
const count = context.mockupScoreQuestionCount;
const valid = context.mockupScoreValid;
const area = questions => ({questions});
assert.equal(count(area(['첫 문항', ' ', '', '두 번째'])), 2);
assert.equal(valid([area(['1','2','3','4',' ']),area(['1','2','3','4','5']),area(['1','2','3','4','5'])]), false);
assert.equal(valid(Array.from({length:3},()=>area(['1','2','3','4','5']))), true);
const billing = context.mockupCouponAdjustedBilling;
const coupon = {couponPlusFrom:'2026-12-09',couponPlusUntil:'2026-12-15'};
assert.equal(billing(coupon,'starter','2026.12.09'),'2026.12.16');
assert.equal(billing(coupon,'starter','2026.12.15'),'2026.12.16');
assert.equal(billing(coupon,'starter','2026.12.16'),'2026.12.16');
assert.equal(billing(coupon,'starter','2026.12.08'),'2026.12.08');
assert.equal(billing(coupon,'team','2026.12.09'),'2026.12.09');
assert.equal(billing({},'starter','2026.12.09'),'2026.12.09');
console.log('Blank report questions and coupon billing checks passed.');
