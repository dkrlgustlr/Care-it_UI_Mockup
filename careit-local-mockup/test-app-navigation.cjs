const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
  page.setDefaultTimeout(5000);
  const base=pathToFileURL(path.join(__dirname,'careit-mockup.html')).href;
  await page.goto(base+'#/journals/new');
  assert.equal(await page.locator('.app-bottom-nav').count(),0);
  assert.equal(await page.locator('.mobile-journal-jump').count(),0);
  await page.locator('.nav-handle').click();
  const drawer=await page.locator('.sidebar').boundingBox();
  assert.ok(drawer.x>0&&drawer.width<390&&drawer.width>=273);
  await page.locator('.mobile-menu-scrim').click({position:{x:10,y:200}});
  assert.equal(await page.locator('.sidebar').isVisible(),false);
  await page.goto(base+'#/reports');
  await page.getByRole('button',{name:'생성 기간'}).click();
  await page.waitForFunction(()=>{const box=document.querySelector('.mockup-report-weeks')?.getBoundingClientRect();return box&&Math.abs(box.bottom-innerHeight)<1;});
  const calendar=await page.locator('.mockup-report-weeks').boundingBox();
  assert.ok(calendar.width>=380&&Math.abs(calendar.y+calendar.height-844)<1,JSON.stringify(calendar));
  await page.locator('.mobile-report-calendar-close').click();
  assert.equal(await page.locator('.mockup-report-weeks').count(),0);
  await page.goto(base+'?previewMode=app#/settings/configuration?recipient=0&template=1');
  assert.equal(await page.locator('.app-bottom-nav').isVisible(),true);
  const back=page.locator('.configuration-mobile-back');
  assert.equal(await back.locator('.mobile-back-icon').isVisible(),true);
  assert.ok((await back.boundingBox()).height>=44);
  await page.locator('#configuration-label-0').fill('수정 중');
  await back.click();
  assert.equal(await page.locator('#mockup-dialog').isVisible(),true);
  await page.locator('#mockup-dialog [data-action="close-dialog"]').click();
  assert.match(page.url(),/configuration/);
  await page.goto(base+'#/journals/new');
  assert.equal(await page.locator('.app-bottom-nav').count(),0);
  await browser.close();
  console.log('App-only navigation and unsaved-edit protection passed');
})().catch(error=>{console.error(error);process.exit(1)});
