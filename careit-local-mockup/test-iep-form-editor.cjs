const assert = require('node:assert/strict');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(pathToFileURL(path.join(__dirname,'careit-mockup.html')).href+'#/iep');
    await page.setViewportSize({width:900,height:900});
    const nextSteps=page.getByRole('button',{name:'다음 단계 보기'});
    await nextSteps.waitFor({state:'visible'});
    await nextSteps.click();
    await page.waitForFunction(()=>document.querySelector('.iew-tabs').scrollLeft>0);
    assert.equal(await page.locator('.iew-tabs').evaluate(el=>getComputedStyle(el).scrollbarWidth),'none');
    await page.setViewportSize({width:1440,height:900});
    await page.locator('[data-iew-id="plan"]').click();
    await page.locator('#iew-longGoal').fill('기존 계획');
    const fieldBefore=await page.locator('#iew-longGoal').boundingBox();
    const headingBefore=await page.locator('h2[data-iew-step="plan"]').boundingBox();
    await page.getByRole('button',{name:'양식 편집',exact:true}).click();
    await page.setViewportSize({width:900,height:900});
    const addStep=page.getByRole('button',{name:'단계 추가',exact:true});
    assert.equal(await addStep.isVisible(),true);
    assert.equal(await addStep.evaluate(el=>el.parentElement.classList.contains('iew-stage-nav')),true);
    assert.equal(await page.getByRole('button',{name:'다음 단계 보기'}).isVisible(),true);
    await page.setViewportSize({width:1440,height:900});
    const fieldAfter=await page.locator('#iew-longGoal').boundingBox();
    const headingAfter=await page.locator('h2[data-iew-step="plan"]').boundingBox();
    assert.equal(fieldAfter.y,fieldBefore.y);
    assert.equal(headingAfter.height,headingBefore.height);
    assert.equal(await page.getByRole('button',{name:'단계 이름 수정',exact:true}).count(),0);
    await page.locator('[data-iew-id="services"]').click();
    await page.getByRole('button',{name:'관련서비스 제목 수정'}).click();
    const dialog=page.locator('#mockup-dialog');
    await dialog.locator('#iew-form-name').fill('지원 서비스');
    await dialog.getByRole('button',{name:'저장'}).click();
    assert.match(await page.locator('[data-iew-id="services"]').innerText(),/지원 서비스/);
    assert.match(await page.locator('h2[data-iew-step="services"]').innerText(),/지원 서비스/);
    await page.locator('[data-iew-id="current"]').click();
    await page.getByRole('button',{name:'현행수준 제목 수정'}).click();
    await dialog.locator('#iew-form-name').fill('현재 수준');
    await dialog.getByRole('button',{name:'저장'}).click();
    assert.match(await page.locator('[data-iew-id="current"]').innerText(),/현재 수준/);
    assert.match(await page.locator('h2[data-iew-step="current"]').innerText(),/현재 수준/);
    await page.locator('[data-iew-id="assessment"]').click();
    await page.getByRole('button',{name:'평가 기준 항목 설정'}).click();
    await dialog.locator('#iew-form-name').fill('확인 기준');
    assert.equal(await dialog.locator('#iew-form-required').count(),0);
    await dialog.getByRole('button',{name:'저장'}).click();
    assert.equal(await page.locator('#iew-assessment-criterion').getAttribute('aria-required'),null);
    await page.locator('[data-iew-id="plan"]').click();
    assert.equal(await page.locator('#iew-longGoal').inputValue(),'기존 계획');
    assert.match(await page.locator('label[for="iew-criterion"]').innerText(),/^확인 기준$/);
    await page.getByRole('button',{name:'완료',exact:true}).click();
    await page.locator('[data-iew-action="save"]').click();
    await page.reload();
    assert.match(await page.locator('[data-iew-id="services"]').innerText(),/지원 서비스/);
    await page.locator('[data-iew-id="plan"]').click();
    assert.equal(await page.locator('#iew-longGoal').inputValue(),'기존 계획');
    assert.match(await page.locator('label[for="iew-criterion"]').innerText(),/^확인 기준$/);
    await page.locator('[data-iew-id="document"]').click();
    assert.equal(await page.getByText('필수 항목 확인').count(),0);
    assert.equal(await page.locator('.iew-review-summary').getByText('확인 기준').count(),0);
    for(const id of ['personal','placement','services','current','plan','meeting','assessment','document']){
      await page.locator(`[data-iew-action="section"][data-iew-id="${id}"]`).click();
      assert.equal(await page.locator('#iew-content .iew-required, #iew-content .iew-optional, #iew-content [aria-required="true"]').count(),0);
    }
    await page.getByRole('link',{name:'케어릿 AI'}).click();
    await page.locator('#ai-chat-input').fill('7번 이름을 월별 평가로 바꿔줘');
    await page.getByRole('button',{name:'메시지 보내기'}).click();
    await page.getByRole('button',{name:'변경 적용',exact:true}).click();
    assert.match(await page.locator('[data-iew-id="assessment"]').innerText(),/월별 평가/);
    await page.locator('[data-iew-id="assessment"]').click();
    assert.match(await page.locator('h2[data-iew-step="assessment"]').innerText(),/월별 평가/);
    await page.locator('#ai-dock [data-action="ai-close"]').click();
    await page.getByRole('button',{name:'양식 편집',exact:true}).click();
    await page.getByRole('button',{name:'단계 추가',exact:true}).click();
    await dialog.locator('#iew-new-step-name').fill('추가 단계');
    await dialog.getByRole('button',{name:'추가',exact:true}).click();
    const added=page.locator('.iew-tabs [data-iew-id^="custom-"]');
    const addedId=await added.getAttribute('data-iew-id');
    await page.locator('#iew-custom-content').fill('추가한 단계 내용');
    await added.dragTo(page.locator('.iew-tabs [data-iew-id="document"]'),{targetPosition:{x:5,y:20}});
    let order=await page.locator('.iew-tabs [data-iew-action="section"]').evaluateAll(buttons=>buttons.map(button=>button.dataset.iewId));
    assert.equal(order.indexOf(addedId),order.indexOf('document')-1);
    await added.press('Alt+ArrowLeft');
    order=await page.locator('.iew-tabs [data-iew-action="section"]').evaluateAll(buttons=>buttons.map(button=>button.dataset.iewId));
    assert.equal(order.indexOf(addedId),order.indexOf('assessment')-1);
    await page.getByRole('button',{name:'완료',exact:true}).click();
    await page.locator('[data-iew-action="save"]').click();
    await page.reload();
    order=await page.locator('.iew-tabs [data-iew-action="section"]').evaluateAll(buttons=>buttons.map(button=>button.dataset.iewId));
    assert.equal(order.indexOf(addedId),order.indexOf('assessment')-1);
    await page.locator(`.iew-tabs [data-iew-id="${addedId}"]`).click();
    assert.equal(await page.locator('#iew-custom-content').inputValue(),'추가한 단계 내용');
    await page.locator('.iew-tabs [data-iew-id="document"]').click();
    assert.equal(await page.getByText('추가한 단계 내용').count(),1);
    await page.locator('.iew-tabs [data-iew-id="plan"]').click();
    await page.locator('#iew-criterion').fill('삭제 검증 내용');
    await page.getByRole('button',{name:'양식 편집',exact:true}).click();
    await page.getByRole('button',{name:'확인 기준 항목 삭제'}).click();
    await dialog.getByRole('button',{name:'삭제',exact:true}).click();
    assert.equal(await page.locator('#iew-criterion').count(),0);
    await page.locator('.iew-tabs [data-iew-id="assessment"]').click();
    assert.equal(await page.locator('#iew-assessment-criterion').count(),0);
    await page.locator(`.iew-tabs [data-iew-id="${addedId}"]`).click();
    await page.getByRole('button',{name:'추가 단계 단계 삭제'}).click();
    await dialog.getByRole('button',{name:'삭제',exact:true}).click();
    assert.equal(await page.locator(`.iew-tabs [data-iew-id="${addedId}"]`).count(),0);
    await page.getByRole('button',{name:'완료',exact:true}).click();
    await page.locator('[data-iew-action="save"]').click();
    await page.reload();
    assert.equal(await page.locator(`.iew-tabs [data-iew-id="${addedId}"]`).count(),0);
    await page.locator('.iew-tabs [data-iew-id="document"]').click();
    assert.equal(await page.getByText('추가한 단계 내용').count(),0);
    assert.equal(await page.getByText('삭제 검증 내용').count(),0);
    await page.locator('.iew-tabs [data-iew-id="services"]').click();
    await page.locator('#iew-therapy').fill('서비스 삭제 검증');
    await page.getByRole('button',{name:'양식 편집',exact:true}).click();
    await page.getByRole('button',{name:'지원 서비스 단계 삭제'}).click();
    await dialog.getByRole('button',{name:'삭제',exact:true}).click();
    assert.equal(await page.locator('.iew-tabs [data-iew-id="services"]').count(),0);
    await page.getByRole('button',{name:'완료',exact:true}).click();
    await page.locator('[data-iew-action="save"]').click();
    await page.reload();
    assert.equal(await page.locator('.iew-tabs [data-iew-id="services"]').count(),0);
    await page.locator('.iew-tabs [data-iew-id="document"]').click();
    assert.equal(await page.getByText('서비스 삭제 검증').count(),0);
    assert.deepEqual(errors,[]);
    console.log('IEP form editor checks passed');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
